function flatten(
  nodes: CategoryNode[],
  parentSlug: string | null = null,
  parentKey: string | null = null,
): PartCategorySeedItem[] {
  return nodes.flatMap((node, sortOrder) => {
    const slug = slugify(node.name);
    const key = parentKey ? `${parentKey}/${slug}` : slug;
    return [
      {
        name: node.name,
        slug,
        parentSlug,
        key,
        parentKey,
        sortOrder,
        isActive: true,
      },
      ...flatten(node.children ?? [], slug, key),
    ];
  });
}

function parseLegacyCatalogue(source: string): PartCategorySeedItem[] {
  const items: PartCategorySeedItem[] = [];
  const keysByDepth = new Map<number, string>();
  const slugsByDepth = new Map<number, string>();
  const indexesByParent = new Map<string, number>();

  for (const line of source.split(/\r?\n/)) {
    const match = line.match(/^\s*(\d+(?:\.\d+){0,2})\.\s+(.+?)\s*$/);
    if (!match) continue;
    const depth = match[1].split('.').length;
    if (depth > 3) continue;
    const name = match[2];
    const slug = slugify(name);
    const parentKey = depth === 1 ? null : (keysByDepth.get(depth - 1) ?? null);
    const parentSlug =
      depth === 1 ? null : (slugsByDepth.get(depth - 1) ?? null);
    if (depth > 1 && (!parentKey || !parentSlug)) continue;
    const key = parentKey ? `${parentKey}/${slug}` : slug;
    const sortOrder = indexesByParent.get(parentKey ?? '__root__') ?? 0;
    indexesByParent.set(parentKey ?? '__root__', sortOrder + 1);
    items.push({
      name,
      slug,
      parentSlug,
      key,
      parentKey,
      sortOrder,
      isActive: true,
    });
    keysByDepth.set(depth, key);
    slugsByDepth.set(depth, slug);
    for (let currentDepth = depth + 1; currentDepth <= 3; currentDepth += 1) {
      keysByDepth.delete(currentDepth);
      slugsByDepth.delete(currentDepth);
    }
  }
  return items;
}

