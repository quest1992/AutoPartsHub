export const catalogV2ForbiddenPositionWords = [
  'передний',
  'задний',
  'левый',
  'правый',
  'верхний',
  'нижний',
  'внутренний',
  'наружный',
] as const;

const catalogV2ForbiddenPositionStems = [
  'передн',
  'задн',
  'лев',
  'прав',
  'верхн',
  'нижн',
  'внутренн',
  'наружн',
] as const;

export type FlatCatalogV2Node = CatalogV2Node & {
  key: string;
  parentKey: string | null;
  depth: number;
  sortOrder: number;
};

export function flattenCatalogV2(): FlatCatalogV2Node[] {
  const result: FlatCatalogV2Node[] = [];
  const visit = (
    nodes: CatalogV2Node[],
    parentKey: string | null,
    depth: number,
  ) => {
    nodes.forEach((node, sortOrder) => {
      const key = parentKey ? `${parentKey}/${node.slug}` : node.slug;
      result.push({ ...node, key, parentKey, depth, sortOrder });
      if (node.children) visit(node.children, key, depth + 1);
    });
  };
  visit(catalogV2, null, 1);
  return result;
}

export function validateCatalogV2() {
  const rows = flattenCatalogV2();
  const errors: string[] = [];
  const keys = new Set<string>();
  const normalizedNames = new Set<string>();

  for (const row of rows) {
    if (row.depth > 3) errors.push(`${row.key}: depth exceeds 3`);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(row.slug))
      errors.push(`${row.key}: invalid slug`);
    if (!row.description.trim()) errors.push(`${row.key}: empty description`);
    if (keys.has(row.key)) errors.push(`${row.key}: duplicate path`);
    keys.add(row.key);

    const normalizedName = row.name
      .toLocaleLowerCase('ru-RU')
      .replace(/ё/g, 'е');
    const scopedName = `${row.parentKey ?? 'root'}:${normalizedName}`;
    if (normalizedNames.has(scopedName))
      errors.push(`${row.key}: duplicate sibling name`);
    normalizedNames.add(scopedName);

    const words = normalizedName.split(/[^а-яa-z0-9]+/u);
    const forbidden = catalogV2ForbiddenPositionStems.find((stem) =>
      words.some((word) => word.startsWith(stem)),
    );
    if (forbidden)
      errors.push(`${row.key}: forbidden position word "${forbidden}"`);
  }
  return errors;
}

export function getCatalogV2Stats() {
  const rows = flattenCatalogV2();
  return {
    roots: rows.filter((row) => row.depth === 1).length,
    groups: rows.filter((row) => row.children?.length).length,
    partTypes: rows.filter((row) => !row.children?.length).length,
    totalCategories: rows.length,
    maxDepth: Math.max(...rows.map((row) => row.depth)),
  };
}
