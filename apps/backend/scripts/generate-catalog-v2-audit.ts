const flaggedNames = new Set<string>([
  ...renames.map(([current]) => current),
  ...removals.map(([name]) => name),
]);

function nodeKind(node: CatalogV2Node, depth: number) {
  if (depth === 1) return 'ROOT';
  return node.children?.length ? 'GROUP' : 'PART_TYPE';
}

function ownerTree(nodes: CatalogV2Node[], depth = 1): string[] {
  return nodes.flatMap((node) => {
    const kind = nodeKind(node, depth);
    const prefix = kind === 'PART_TYPE' ? '- [ ]' : `${'#'.repeat(depth + 1)}`;
    return [
      `${prefix} ${node.name}`,
      ...(kind === 'PART_TYPE' ? [] : ['']),
      ...ownerTree(node.children ?? [], depth + 1),
    ];
  });
}

function readyByRoot() {
  const rows = flattenCatalogV2();
  return catalogV2
    .map((root) => {
      const names = rows
        .filter(
          (row) =>
            row.key.startsWith(`${root.slug}/`) &&
            !row.children?.length &&
            !flaggedNames.has(row.name),
        )
        .map((row) => row.name);
      return `### ${root.name}\n\n${names.join('; ')}.`;
    })
    .join('\n\n');
}

function aliasesTable() {
  return flattenCatalogV2()
    .filter((row) => !row.children?.length)
    .map(
      (row) =>
        `| ${row.name} | ${aliases[row.name] ?? '— (безопасный общеупотребительный синоним не выявлен)'} |`,
    )
    .join('\n');
}

