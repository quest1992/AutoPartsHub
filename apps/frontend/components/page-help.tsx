const fallback: HelpContent = {
  title: "Как пользоваться страницей",
  purpose: "Это рабочий раздел AutoStock.",
  steps: [
    "Заполните обязательные поля, отмеченные звёздочкой.",
    "Проверьте введённые данные.",
    "Сохраняйте изменения только после проверки.",
  ],
  tip: "Если действие непонятно или данные отсутствуют, не создавайте дубликат — сначала воспользуйтесь поиском.",
};

export function PageHelp() {
  const pathname = usePathname();
  const [open, setOpen] = useState(false);
  const content =
    help.find((item) => item.match(pathname))?.content ?? fallback;

  useEffect(() => {
    if (!open) return;
    const close = (event: KeyboardEvent) =>
      event.key === "Escape" && setOpen(false);
    window.addEventListener("keydown", close);
    return () => window.removeEventListener("keydown", close);
  }, [open]);

  if (pathname === "/login" || pathname === "/" || pathname === "/forbidden")
    return null;

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className="fixed bottom-5 right-5 z-40 rounded-full bg-blue-600 px-5 py-3 font-semibold text-white shadow-lg hover:bg-blue-700"
        aria-label="Открыть инструкцию по странице"
      >
        ? Как пользоваться
      </button>
      {open && (
        <div
          className="fixed inset-0 z-[100] grid place-items-center bg-slate-950/55 p-4"
          role="presentation"
          onMouseDown={(event) =>
            event.target === event.currentTarget && setOpen(false)
          }
        >
          <section
            role="dialog"
            aria-modal="true"
            aria-labelledby="page-help-title"
            className="max-h-[85vh] w-full max-w-xl overflow-y-auto rounded-2xl bg-white p-6 shadow-2xl"
          >
            <div className="flex items-start justify-between gap-4">
              <div>
                <p className="text-sm font-medium text-blue-700">
                  Инструкция по текущей странице
                </p>
                <h2
                  id="page-help-title"
                  className="mt-1 text-2xl font-bold text-slate-900"
                >
                  {content.title}
                </h2>
              </div>
              <button
                type="button"
                onClick={() => setOpen(false)}
                className="rounded-lg border px-3 py-2 text-slate-600"
                aria-label="Закрыть инструкцию"
              >
                Закрыть
              </button>
            </div>
            <p className="mt-4 text-slate-700">{content.purpose}</p>
            <ol className="mt-5 space-y-3">
              {content.steps.map((step, index) => (
                <li key={step} className="flex gap-3">
                  <span className="grid h-7 w-7 shrink-0 place-items-center rounded-full bg-blue-100 font-semibold text-blue-700">
                    {index + 1}
                  </span>
                  <span className="pt-0.5 text-slate-800">{step}</span>
                </li>
              ))}
            </ol>
            {content.tip && (
              <p className="mt-5 rounded-xl bg-amber-50 p-4 text-sm text-amber-900">
                <b>Важно:</b> {content.tip}
              </p>
            )}
          </section>
        </div>
      )}
    </>
  );
}
